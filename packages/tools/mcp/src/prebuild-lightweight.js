import { buildSampleIndex } from './sample-index.js';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

async function prebuildSampleIndex() {
	try {
		console.log('Building sample index...');
		const index = await buildSampleIndex();

		// Create lightweight index (only metadata, no code)
		const lightweightIndex = {
			entries: index.entries.map((entry) => ({
				id: entry.id,
				group: entry.group,
				name: entry.name,
				path: entry.path,
				// Don't include the actual code to keep it small
			})),
			generatedAt: index.generatedAt,
		};

		// Create full index for local development
		const fullIndex = {
			entries: index.entries,
			generatedAt: index.generatedAt,
		};

		// Write full index for local development
		const localOutputPath = path.join(__dirname, '../netlify/sample-index.json');
		writeFileSync(localOutputPath, JSON.stringify(fullIndex, null, 2));

		// Write full index to functions directory
		const embeddedOutputPath = path.join(__dirname, '../netlify/functions/sample-index.json');
		writeFileSync(embeddedOutputPath, JSON.stringify(fullIndex, null, 2));

		// Write lightweight index as JavaScript module for Netlify
		const jsContent = `// Auto-generated lightweight sample index
// This file is generated by the prebuild script

export const SAMPLE_INDEX_METADATA = ${JSON.stringify(lightweightIndex)};

// Sample code lookup - this would need to be loaded from the repository
export const SAMPLE_CODE_LOOKUP = new Map([
${index.entries.map((entry) => `  ['${entry.id}', ${JSON.stringify(entry.code)}]`).join(',\n')}
]);
`;
		const jsOutputPath = path.join(__dirname, './netlify/sample-index-data.js');
		writeFileSync(jsOutputPath, jsContent);

		console.log(`Sample index built with ${index.entries.length} entries`);
		console.log(`Lightweight index saved to: ${jsOutputPath}`);
		console.log(`Full index saved to: ${localOutputPath}`);
		console.log(`Full index embedded to: ${embeddedOutputPath}`);
	} catch (error) {
		console.error('Failed to build sample index:', error);
		process.exit(1);
	}
}

prebuildSampleIndex();
