#!/usr/bin/env node

import { existsSync } from 'node:fs';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const PACKAGE_ROOT = path.resolve(__dirname, '..');
const CACHE_DIR = path.join(PACKAGE_ROOT, '.cache');
const CACHE_FILE = path.join(CACHE_DIR, 'samples.json');
const DIST_DIR = path.join(PACKAGE_ROOT, 'dist');
const API_DIR = path.join(PACKAGE_ROOT, 'api');

const stage = process.argv[2];

function getCommitMetadata() {
        const commit = process.env.GITHUB_SHA || process.env.VERCEL_GIT_COMMIT_SHA || null;
        const branch = process.env.GITHUB_REF_NAME || process.env.VERCEL_GIT_COMMIT_REF || null;
        const repoUrl = process.env.GITHUB_REPOSITORY ? `https://github.com/${process.env.GITHUB_REPOSITORY}` : null;

        return { commit, branch, repoUrl };
}

function toPlainCounts(counts) {
        if (!counts) {
                return {
                        total: 0,
                        totalSamples: 0,
                        totalDocs: 0,
                        byKind: {},
                };
        }

        const byKind = Object.create(null);
        if (counts.byKind instanceof Map) {
                for (const [key, value] of counts.byKind.entries()) {
                        byKind[key] = value;
                }
        } else if (typeof counts.byKind === 'object' && counts.byKind) {
                        for (const [key, value] of Object.entries(counts.byKind)) {
                                if (typeof value === 'number') {
                                        byKind[key] = value;
                                }
                        }
        }

        return {
                total: counts.total ?? 0,
                totalSamples: counts.totalSamples ?? byKind.sample ?? 0,
                totalDocs: counts.totalDocs ?? byKind.doc ?? 0,
                byKind,
        };
}

async function runPrebuild() {
        console.log('[mcp/build] Collecting sample index from repository…');
        const { buildSampleIndex } = await import('../src/_old/sample-index-runtime.js');
        const index = await buildSampleIndex();

        const sanitizedEntries = index.entries.map((entry) => {
                const { absolutePath, kind, ...rest } = entry;
                const normalizedKind = kind === 'doc' ? 'doc' : 'sample';
                return {
                        ...rest,
                        kind: normalizedKind,
                        // Normalise line endings to keep deployments deterministic
                        code: typeof rest.code === 'string' ? rest.code.replace(/\r\n?/g, '\n') : rest.code,
                };
        });

        const counts = toPlainCounts(index.counts);
        counts.total = sanitizedEntries.length;
        counts.totalSamples = sanitizedEntries.filter((entry) => entry.kind !== 'doc').length;
        counts.totalDocs = sanitizedEntries.filter((entry) => entry.kind === 'doc').length;

        const payload = {
                metadata: {
                        generatedAt: new Date().toISOString(),
                        buildMode: 'github-actions',
                        counts,
                        repo: getCommitMetadata(),
                },
                entries: sanitizedEntries,
        };

        await mkdir(CACHE_DIR, { recursive: true });
        await writeFile(CACHE_FILE, JSON.stringify(payload, null, 2), 'utf8');

        console.log(`[mcp/build] Sample index cached with ${sanitizedEntries.length} entries.`);
}

async function createModuleFile(targetPath, data) {
        const moduleContent = `// Auto-generated by scripts/build-sample-index.mjs\nexport const sampleData = ${JSON.stringify(data, null, 2)};\nexport default sampleData;\n`;
        await writeFile(targetPath, moduleContent, 'utf8');
}

async function createCjsModuleFile(targetPath, data) {
        const moduleContent = `'use strict';\nObject.defineProperty(exports, '__esModule', { value: true });\nexports.sampleData = ${JSON.stringify(data, null, 2)};\nexports.default = exports.sampleData;\n`;
        await writeFile(targetPath, moduleContent, 'utf8');
}

async function runPostbuild() {
        if (!existsSync(CACHE_FILE)) {
                throw new Error(`Missing cache file ${CACHE_FILE}. Run with the "pre" stage before postbuild.`);
        }

        const raw = await readFile(CACHE_FILE, 'utf8');
        const payload = JSON.parse(raw);

        await mkdir(DIST_DIR, { recursive: true });

        const samplesJsonPath = path.join(DIST_DIR, 'samples.json');
        await writeFile(samplesJsonPath, JSON.stringify(payload, null, 2), 'utf8');
        console.log(`[mcp/build] Wrote ${payload.entries.length} entries to ${samplesJsonPath}`);

        const metadataPath = path.join(DIST_DIR, 'samples.meta.json');
        await writeFile(metadataPath, JSON.stringify(payload.metadata, null, 2), 'utf8');

        await createModuleFile(path.join(DIST_DIR, 'samples.mjs'), payload);
        await createCjsModuleFile(path.join(DIST_DIR, 'samples.cjs'), payload);

        // Provide module for Vercel API TypeScript sources to import without bundling
        if (existsSync(API_DIR)) {
                await createModuleFile(path.join(API_DIR, 'samples.mjs'), payload);
        }

        // Clean cache after copying to dist to avoid stale data in future builds
        await rm(CACHE_FILE, { force: true });
        const cacheContents = await readDirSafe(CACHE_DIR);
        if (cacheContents.length === 0) {
                await rm(CACHE_DIR, { force: true, recursive: true });
        }
}

async function readDirSafe(directory) {
        try {
                return await readdir(directory);
        } catch (error) {
                if ((error instanceof Error && 'code' in error && error.code === 'ENOENT') || error?.code === 'ENOTDIR') {
                        return [];
                }
                throw error;
        }
}

(async () => {
        try {
                if (stage === 'pre') {
                        await runPrebuild();
                } else if (stage === 'post') {
                        await runPostbuild();
                } else {
                        console.error('[mcp/build] Unknown stage. Use "pre" or "post".');
                        process.exitCode = 1;
                }
        } catch (error) {
                console.error('[mcp/build] Failed to process sample index:', error);
                process.exitCode = 1;
        }
})();
