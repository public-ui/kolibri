const NULL_CHARACTERS = new RegExp(String.fromCharCode(0), 'g');
const REPLACEMENT_CHARACTER = String.fromCharCode(65533);

const NAMED_ENTITIES: Record<string, string> = {
	amp: '&',
	apos: "'",
	gt: '>',
	lt: '<',
	nbsp: String.fromCharCode(160),
	quot: '"',
};

const decodeCodePoint = (code: number): string | undefined =>
	Number.isInteger(code) && code >= 32 && code <= 0x10ffff && !(code >= 0xd800 && code <= 0xdfff) ? String.fromCodePoint(code) : undefined;

/**
 * Resolves numeric and the most common named character references, so pre-escaped label text
 * keeps rendering its characters. Every other reference stays visible text.
 */
const decodeEntities = (str: string): string =>
	str
		.replace(/&#(\d+);/g, (reference: string, code: string) => decodeCodePoint(Number.parseInt(code, 10)) ?? reference)
		.replace(/&#x([0-9a-f]+);/gi, (reference: string, code: string) => decodeCodePoint(Number.parseInt(code, 16)) ?? reference)
		.replace(/&([a-z]+);/gi, (reference: string, name: string) => NAMED_ENTITIES[name.toLowerCase()] ?? reference);

/**
 * Escapes every character that could start an HTML tag or attribute, so the rendered label can
 * only contain tags generated by `md` itself.
 */
const escapeHtml = (str: string): string => str.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/**
 * Whitespace or ASCII punctuation without the underscore. `_` and `__` only open and close next
 * to these characters, so emphasis inside a word like `some_file_name` stays literal text.
 */
const DELIMITER_NEIGHBOUR = '\\s!-/:-@\\[-^`{-~';
const OPENER_PREFIX = `(^|[${DELIMITER_NEIGHBOUR}])`;
const CLOSER_SUFFIX = `(?=$|[${DELIMITER_NEIGHBOUR}])`;

/**
 * The content between two delimiters may not start or end with whitespace, so `** bold **`
 * stays literal text.
 */
const CONTENT = '\\S(?:[\\s\\S]*\\S)?';

const HARD_BREAK = /[ \t]{2,}\n/g;
const STRIKETHROUGH = new RegExp(`~~(${CONTENT})~~`, 'g');
const ASTERISK_STRONG = new RegExp(`\\*\\*(${CONTENT})\\*\\*`, 'g');
const ASTERISK_EM = /\*([^\s*](?:[^*]*[^\s*])?)\*/g;
const TRIPLE_ASTERISK_STRONG_EM = new RegExp(`\\*\\*\\*(${CONTENT})\\*\\*\\*`, 'g');
const UNDERSCORE_STRONG = new RegExp(`${OPENER_PREFIX}__(${CONTENT})__${CLOSER_SUFFIX}`, 'g');
const UNDERSCORE_EM = new RegExp(`${OPENER_PREFIX}_([^\\s_](?:[^_]*[^\\s_])?)_${CLOSER_SUFFIX}`, 'g');
const TRIPLE_UNDERSCORE_STRONG_EM = new RegExp(`${OPENER_PREFIX}___(${CONTENT})___${CLOSER_SUFFIX}`, 'g');

const formatInline = (str: string): string =>
	str
		.replace(HARD_BREAK, '<br>\n')
		.replace(TRIPLE_ASTERISK_STRONG_EM, '<em><strong>$1</strong></em>')
		.replace(TRIPLE_UNDERSCORE_STRONG_EM, '$1<em><strong>$2</strong></em>')
		.replace(STRIKETHROUGH, '<s>$1</s>')
		.replace(ASTERISK_STRONG, '<strong>$1</strong>')
		.replace(UNDERSCORE_STRONG, '$1<strong>$2</strong>')
		.replace(ASTERISK_EM, '<em>$1</em>')
		.replace(UNDERSCORE_EM, '$1<em>$2</em>');

/**
 * Renders the Markdown subset documented on `AllowMarkdownPropType` as inline HTML: bold,
 * italic, strikethrough, inline code and hard line breaks. Block syntax stays literal text.
 *
 * The whole input is escaped before the first tag is generated, so raw HTML always stays
 * visible text and the output only contains tags generated here.
 */
export const md = (str: string): string => {
	const escapedMarkers: string[] = [];

	return (
		escapeHtml(decodeEntities(str.replace(/\r\n?/g, '\n').replace(NULL_CHARACTERS, REPLACEMENT_CHARACTER)))
			// A backslash keeps the following syntax marker visible as text instead of formatting the label.
			.replace(/\\([\\`*_~[\]()#+\-.!>{}])/g, (_match: string, marker: string) => {
				escapedMarkers.push(marker);
				return `<${escapedMarkers.length - 1}>`;
			})
			.split(/(`[^`]+`)/)
			.map((segment: string, index: number) => (index % 2 === 0 ? formatInline(segment) : `<code>${segment.slice(1, -1)}</code>`))
			.join('')
			.replace(/<(\d+)>/g, (_match: string, index: string) => escapedMarkers[Number.parseInt(index, 10)] ?? '')
	);
};
